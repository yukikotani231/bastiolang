#!/usr/bin/env python3
"""The library reference: docs/lib/*.md, generated from core/ and std/.

usage: tests/libref.py --write           regenerate docs/lib/*.md and the
                                          module table in docs/core.md
       tests/libref.py --check           fail if they are out of date, or if
                                          a library function has no doc
                                          comment or no example calls it
       tests/libref.py --examples DIR    write each module's examples into
                                          DIR as one program per module, and
                                          print "module program" lines

The reference is never edited by hand. Each page is built from one library
file: the comment at its top, then every type, constant and function with
its `///` doc comment and its contract (`requires` and `ensures`) exactly
as the compiler checks it, then the spec fns those contracts use.

Examples live in the doc comments, between two `/// ```` lines. An example
is the body of a function that returns `u64`: it returns 0 at the end
(added for it) and anything else to fail. It may use `con` (a `&Serial`)
and `host` (a `&Host`). `assert` lines are proved at compile time, so
an example shows which facts a contract gives its caller; other checks run.
tests/run.sh builds every module's examples into one program, verifies it
and runs it, so a page never shows an example that does not work.

A doc comment that starts with "Internal:" marks a helper the module's
other functions use; the page lists it last, and it needs no example.
Every other function must be called by some example on its page.
"""

import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LIBS = ["core", "std"]
OUT = "docs/lib"
INDEX_DOC = "docs/core.md"
BEGIN = "<!-- libref: modules (generated by tests/libref.py --write) -->"
END = "<!-- libref: end -->"
ITEM = re.compile(r"^(opaque spec fn|spec fn|fn|struct|enum|const)\s+([A-Za-z_][A-Za-z0-9_]*)")


class Item:
    def __init__(self, kind, name, code, doc, example):
        self.kind, self.name, self.code, self.doc, self.example = kind, name, code, doc, example

    @property
    def internal(self):
        return self.doc.startswith("Internal:")

    @property
    def spec(self):
        return "spec fn" in self.kind


def parse_doc(lines, where):
    """Split `///` lines into prose and an optional example."""
    prose, example, inside, seen = [], [], False, False
    for line in lines:
        if line.strip() == "```":
            if seen and not inside:
                sys.exit(f"libref: {where}: more than one example")
            inside = not inside
            seen = True
            continue
        (example if inside else prose).append(line)
    if inside:
        sys.exit(f"libref: {where}: example not closed")
    return "\n".join(prose).strip(), example


def parse(path):
    with open(os.path.join(ROOT, path)) as f:
        lines = f.read().split("\n")
    i = 0
    header = []
    while i < len(lines) and lines[i].startswith("//") and not lines[i].startswith("///"):
        header.append(lines[i][3:] if lines[i].startswith("// ") else lines[i][2:])
        i += 1
    imports, items, doc = [], [], []
    while i < len(lines):
        line = lines[i]
        if line.startswith("///"):
            doc.append(line[4:] if line.startswith("/// ") else line[3:])
            i += 1
            continue
        m = ITEM.match(line)
        if line.startswith("import "):
            imports.append(line.split('"')[1])
        elif m:
            kind, name = m.group(1), m.group(2)
            start = i
            if kind in ("fn",):
                # The signature and contract, up to the `{` of the body.
                while not (lines[i] == "{" or lines[i].endswith("{")):
                    i += 1
                code = lines[start:i] + ([] if lines[i] == "{" else [lines[i][:-1].rstrip()])
                while lines[i] != "}":
                    i += 1
            elif line.rstrip().endswith("{"):
                while lines[i] != "}":
                    i += 1
                code = lines[start:i + 1]
            else:
                code = [line]
            text, example = parse_doc(doc, f"{path}: {name}")
            items.append(Item(kind, name, "\n".join(code), text, example))
        elif line.strip() and not line.startswith("//"):
            pass
        doc = [] if not line.startswith("///") else doc
        i += 1
    return header, imports, items


def page_name(path):
    return path.replace("/", "-").replace(".bastio", ".md")


def first_sentence(text):
    para = text.split("\n\n")[0].replace("\n", " ")
    m = re.match(r"(.*?[.:])(\s|$)", para)
    s = m.group(1) if m else para
    return s.rstrip(":") + ("." if s.endswith(":") else "")


def resolve_imports(path, seen=None):
    """Every library file `path` brings in, in load order."""
    seen = [] if seen is None else seen
    _, imports, _ = parse(path)
    for imp in imports:
        dep = os.path.normpath(os.path.join(os.path.dirname(path), imp))
        if dep not in seen:
            resolve_imports(dep, seen)
            seen.append(dep)
    return seen


def modules():
    out = []
    for lib in LIBS:
        for f in sorted(os.listdir(os.path.join(ROOT, lib))):
            if f.endswith(".bastio"):
                out.append(f"{lib}/{f}")
    return out


def render(path):
    header, _, items = parse(path)
    title = header[0].split(":", 1) if header else [path, ""]
    intro = [title[1].strip()] + header[1:] if len(title) > 1 else header[1:]
    deps = resolve_imports(path)
    out = [f"# {path}", "",
           f"<!-- Generated by tests/libref.py from {path}: edit the source, then run tests/libref.py --write. -->",
           ""]
    text = "\n".join(intro).strip()
    out += [text[:1].upper() + text[1:], ""]
    imp = f'`import "{path}";`'
    if deps:
        imp += " also loads " + ", ".join(f"[{d}]({page_name(d)})" for d in deps) + "."
    out += [imp, ""]
    types = [it for it in items if it.kind in ("struct", "enum", "const")]
    fns = [it for it in items if it.kind == "fn" and not it.internal]
    specs = [it for it in items if it.spec]
    internals = [it for it in items if it.kind == "fn" and it.internal]
    if fns:
        out += ["| Function | |", "| --- | --- |"]
        for it in fns:
            out.append(f"| [`{it.name}`](#{it.name}) | {first_sentence(it.doc)} |")
        out.append("")
    out += ["Every example below is built, verified and run by `tests/run.sh`. "
            "An `assert` in one is proved at compile time from the contracts above it.", ""]

    def section(title, group):
        if not group:
            return
        out.extend([f"## {title}", ""])
        for it in group:
            out.extend([f"### `{it.name}`", "", "```bastio", it.code, "```", ""])
            if it.doc:
                out.extend([it.doc, ""])
            if it.example:
                out.extend(["Example:", "", "```bastio"] + it.example + ["```", ""])

    section("Types and constants", types)
    section("Functions", fns)
    section("Specification functions", specs)
    section("Internals", internals)
    return "\n".join(out).rstrip() + "\n"


def module_table():
    rows = ["| Module | |", "| --- | --- |"]
    for path in modules():
        header, _, _ = parse(path)
        para = " ".join(header[:header.index("")] if "" in header else header)
        summary = first_sentence(para.split(":", 1)[1].strip()) if ":" in para else ""
        summary = summary[0].upper() + summary[1:] if summary else ""
        rows.append(f"| [`{path}`](lib/{page_name(path)}) | {summary} |")
    return "\n".join(rows)


def expected():
    pages = {os.path.join(OUT, page_name(p)): render(p) for p in modules()}
    with open(os.path.join(ROOT, INDEX_DOC)) as f:
        doc = f.read()
    if BEGIN not in doc or END not in doc:
        sys.exit(f"libref: {INDEX_DOC} has no {BEGIN} ... {END} block")
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    pages[INDEX_DOC] = head + BEGIN + "\n" + module_table() + "\n" + END + tail
    return pages


def problems():
    bad = []
    for path in modules():
        _, _, items = parse(path)
        examples = "\n".join("\n".join(it.example) for it in items)
        for it in items:
            if it.kind == "fn" and not it.doc:
                bad.append(f"{path}: {it.name} has no doc comment")
            if it.kind == "fn" and not it.internal and \
                    not re.search(r"\b" + it.name + r"\s*[\[(]", examples):
                bad.append(f"{path}: no example calls {it.name}")
    return bad


def write_examples(outdir):
    os.makedirs(outdir, exist_ok=True)
    for path in modules():
        _, _, items = parse(path)
        exs = [it for it in items if it.example]
        if not exs:
            continue
        prog = ["// Generated by tests/libref.py --examples from " + path, f'import "{path}";', ""]
        calls = []
        for k, it in enumerate(exs):
            body = "\n".join(it.example)
            params, args = [], []
            if re.search(r"\bcon\b", body):
                params.append("con: &Serial"); args.append("con")
            if re.search(r"\bhost\b", body):
                params.append("host: &Host"); args.append("host")
            fn = f"example_{k}_{it.name}"
            prog.append(f"fn {fn}({', '.join(params)}) -> u64 {{")
            prog += ["  " + l if l else l for l in it.example]
            prog += ["  return 0;", "}", ""]
            calls.append(f"  if {fn}({', '.join(args)}) != 0 {{ return {k + 1}; }}")
        prog.append("fn main(con: &mut Serial, host: &mut Host) -> u64 {")
        prog += calls + ["  return 0;", "}", ""]
        name = page_name(path).replace(".md", ".bastio")
        with open(os.path.join(outdir, name), "w") as f:
            f.write("\n".join(prog))
        print(path, os.path.join(outdir, name), " ".join(it.name for it in exs))


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode == "--examples":
        write_examples(sys.argv[2])
        return
    pages = expected()
    if mode == "--write":
        os.makedirs(os.path.join(ROOT, OUT), exist_ok=True)
        for name in os.listdir(os.path.join(ROOT, OUT)):
            if name.endswith(".md") and os.path.join(OUT, name) not in pages:
                os.remove(os.path.join(ROOT, OUT, name))
        for name, text in pages.items():
            with open(os.path.join(ROOT, name), "w") as f:
                f.write(text)
    stale = []
    for name, text in pages.items():
        p = os.path.join(ROOT, name)
        if not os.path.exists(p) or open(p).read() != text:
            stale.append(name)
    extra = [n for n in os.listdir(os.path.join(ROOT, OUT))
             if n.endswith(".md") and os.path.join(OUT, n) not in pages] \
        if os.path.isdir(os.path.join(ROOT, OUT)) else []
    bad = problems()
    with open(os.path.join(ROOT, "site/SUMMARY.md")) as f:
        summary = f.read()
    for name in pages:
        if name.startswith(OUT) and f"(lib-{os.path.basename(name)})" not in summary:
            bad.append(f"site/SUMMARY.md does not list {name} (as lib-{os.path.basename(name)})")
    for name in stale + [os.path.join(OUT, n) for n in extra]:
        print(f"libref: {name} is out of date: run tests/libref.py --write")
    for b in bad:
        print(f"libref: {b}")
    if stale or extra or bad:
        sys.exit(1)
    print(f"libref: {len(pages) - 1} pages up to date, every function documented and called by an example")


main()
