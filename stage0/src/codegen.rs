// C backend (stage0 only; the self-hosted compiler will emit x86-64 directly).
//
// Zero overhead: everything the verifier proved is erased here. There are no
// bounds checks, no overflow checks and no length bookkeeping beyond the
// `len` field the program itself can read. Specifications, invariants and
// asserts produce no code at all.

use crate::ast::*;

pub fn emit(p: &Program) -> String {
    let mut out = String::new();
    out.push_str(PRELUDE);
    for f in &p.fns {
        out.push_str(&format!("{};\n", proto(f)));
    }
    out.push('\n');
    for f in &p.fns {
        out.push_str(&format!("{} {{\n", proto(f)));
        for s in &f.body {
            stmt(s, 1, &mut out);
        }
        out.push_str("}\n\n");
    }
    out.push_str("int main(void) { return (int)f_main(); }\n");
    out
}

const PRELUDE: &str = r#"/* generated by bastioc0 -- do not edit */
#include <stdint.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>

typedef struct { uint64_t len; uint64_t *data; } bst_buf;

static bst_buf bst_alloc(uint64_t n) {
    bst_buf b;
    b.len = n;
    b.data = (uint64_t *)calloc(n ? n : 1, sizeof(uint64_t));
    if (!b.data) { fputs("Bastio: out of memory\n", stderr); abort(); }
    return b;
}
static inline bst_buf bst_set(bst_buf b, uint64_t i, uint64_t v) { b.data[i] = v; return b; }
static inline void bst_free(bst_buf b) { free(b.data); }
static inline void bst_print(uint64_t v) { printf("%llu\n", (unsigned long long)v); }

"#;

fn cty(t: &Type) -> &'static str {
    match t {
        Type::U64 => "uint64_t",
        Type::Bool => "bool",
        Type::Unit => "void",
        Type::Buf | Type::RefBuf => "bst_buf",
    }
}

fn proto(f: &FnDef) -> String {
    let params: Vec<String> = f.params.iter().map(|p| format!("{} v_{}", cty(&p.ty), p.name)).collect();
    let ps = if params.is_empty() { "void".to_string() } else { params.join(", ") };
    format!("static {} f_{}({})", cty(&f.ret), f.name, ps)
}

fn ind(n: usize) -> String {
    "    ".repeat(n)
}

fn stmt(s: &Stmt, d: usize, out: &mut String) {
    match &s.kind {
        StmtKind::Let { name, ty, init, .. } => {
            out.push_str(&format!("{}{} v_{} = {};\n", ind(d), cty(ty.as_ref().expect("typed by checker")), name, expr(init)));
        }
        StmtKind::Assign { name, value } => out.push_str(&format!("{}v_{} = {};\n", ind(d), name, expr(value))),
        StmtKind::If { cond, then_b, else_b } => {
            out.push_str(&format!("{}if ({}) {{\n", ind(d), expr(cond)));
            for s in then_b {
                stmt(s, d + 1, out);
            }
            if else_b.is_empty() {
                out.push_str(&format!("{}}}\n", ind(d)));
            } else {
                out.push_str(&format!("{}}} else {{\n", ind(d)));
                for s in else_b {
                    stmt(s, d + 1, out);
                }
                out.push_str(&format!("{}}}\n", ind(d)));
            }
        }
        StmtKind::While { cond, body, .. } => {
            out.push_str(&format!("{}while ({}) {{\n", ind(d), expr(cond)));
            for s in body {
                stmt(s, d + 1, out);
            }
            out.push_str(&format!("{}}}\n", ind(d)));
        }
        StmtKind::Return(Some(e)) => out.push_str(&format!("{}return {};\n", ind(d), expr(e))),
        StmtKind::Return(None) => out.push_str(&format!("{}return;\n", ind(d))),
        StmtKind::Assert(_) => {} // ghost: proved at compile time, erased
        StmtKind::Expr(e) => out.push_str(&format!("{}{};\n", ind(d), expr(e))),
    }
}

fn expr(e: &Expr) -> String {
    match &e.kind {
        ExprKind::Int(v) => format!("UINT64_C({})", v),
        ExprKind::Bool(b) => b.to_string(),
        ExprKind::Var(n) => format!("v_{}", n),
        ExprKind::Not(x) => format!("(!{})", expr(x)),
        ExprKind::Bin(op, a, b) => format!("({} {} {})", expr(a), op.text(), expr(b)),
        ExprKind::Forall(..) => unreachable!("specification only"),
        ExprKind::Call(name, args) => {
            let a: Vec<String> = args.iter().map(expr).collect();
            match name.as_str() {
                "len" => format!("{}.len", a[0]),
                "get" => format!("{}.data[{}]", a[0], a[1]),
                "alloc" | "set" | "free" | "print" => format!("bst_{}({})", name, a.join(", ")),
                _ => format!("f_{}({})", name, a.join(", ")),
            }
        }
    }
}
