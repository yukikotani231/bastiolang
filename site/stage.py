"""Copy the repository's documentation into the mdBook source directory.

usage: stage.py REPO_ROOT OUT_DIR

PAGES maps a repository file to its page in the book. A relative Markdown
link in a copied file is resolved against the file's place in the repository:
if it lands on another file in PAGES it becomes a link to that page, and if
it lands on any other file or directory of the repository it becomes a link
to it on GitHub. Links that resolve to nothing (code that happens to look
like a link, such as `cast[u64](x)`) are left alone.
"""

import os
import re
import sys

REPO_URL = "https://github.com/yukikotani231/bastiolang"

PAGES = {
    "README.md": "introduction.md",
    "docs/tutorial.md": "tutorial.md",
    "docs/tutorial-bits.md": "tutorial-bits.md",
    "docs/tutorial-capabilities.md": "tutorial-capabilities.md",
    "docs/tutorial-shared.md": "tutorial-shared.md",
    "docs/toolchain.md": "toolchain.md",
    "docs/trusted-base.md": "trusted-base.md",
    "docs/ir.md": "ir.md",
    "docs/proof-failures.md": "proof-failures.md",
    "docs/language.md": "language.md",
    "docs/integers.md": "integers.md",
    "docs/concurrency.md": "concurrency.md",
    "docs/core.md": "core.md",
    "docs/packages.md": "packages.md",
    "examples/base64/README.md": "examples-base64.md",
    "examples/utf8/README.md": "examples-utf8.md",
    "examples/leb128/README.md": "examples-leb128.md",
    "examples/der/README.md": "examples-der.md",
    "examples/qoi/README.md": "examples-qoi.md",
    "examples/http/README.md": "examples-http.md",
    "ROADMAP.md": "roadmap.md",
    "CONTRIBUTING.md": "contributing.md",
    "CHANGELOG.md": "changelog.md",
    "docs/releasing.md": "releasing.md",
    "docs/bootstrap.md": "bootstrap.md",
    "docs/architecture.md": "architecture.md",
}
# The library reference, one page per module (generated by tests/libref.py).
_here = os.path.dirname(os.path.abspath(__file__))
for _f in sorted(os.listdir(os.path.join(_here, "..", "docs", "lib"))):
    if _f.endswith(".md"):
        PAGES["docs/lib/" + _f] = "lib-" + _f

LINK = re.compile(r"(\]\()([^)\s]+)(\))")
FENCE = re.compile(r"^\s*(```|~~~)")


def rewrite(root, src, line):
    def fix(m):
        target = m.group(2)
        if re.match(r"[a-z]+:", target) or target.startswith("#"):
            return m.group(0)
        path, _, anchor = target.partition("#")
        rel = os.path.normpath(os.path.join(os.path.dirname(src), path))
        if rel.startswith("..") or not os.path.exists(os.path.join(root, rel)):
            return m.group(0)
        frag = "#" + anchor if anchor else ""
        if rel in PAGES:
            new = PAGES[rel] + frag
        else:
            kind = "tree" if os.path.isdir(os.path.join(root, rel)) else "blob"
            new = f"{REPO_URL}/{kind}/main/{rel}{frag}"
        return m.group(1) + new + m.group(3)

    # Inline code spans are left as they are.
    parts = line.split("`")
    for i in range(0, len(parts), 2):
        parts[i] = LINK.sub(fix, parts[i])
    return "`".join(parts)


def main():
    root, out = sys.argv[1], sys.argv[2]
    for src, page in PAGES.items():
        with open(os.path.join(root, src)) as f:
            lines = f.read().split("\n")
        fenced = False
        for i, line in enumerate(lines):
            if FENCE.match(line):
                fenced = not fenced
            elif not fenced:
                lines[i] = rewrite(root, src, line)
        with open(os.path.join(out, page), "w") as f:
            f.write("\n".join(lines))


main()
